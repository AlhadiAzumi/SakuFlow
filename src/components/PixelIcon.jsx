function buildPaths(name) {
  const rows = SPRITES[name] || SPRITES.other
  const grouped = {}

  rows.forEach((row, y) => {
    for (let x = 0; x < SIZE; x += 1) {
      const token = row[x] || '.'
      if (token === '.' || !PALETTE[token]) continue
      if (!grouped[token]) grouped[token] = []
      grouped[token].push(`M${x} ${y}h1v1h-1z`)
    }
  })

  return Object.entries(grouped).map(([token, parts]) => ({
    color: PALETTE[token],
    d: parts.join(''),
  }))
}

export default function PixelIcon({ name, size = 16, className = '', title, ...props }) {
  const paths = useMemo(() => buildPaths(name), [name])

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${SIZE} ${SIZE}`}
      shapeRendering="crispEdges"
      className={`inline-block shrink-0 ${className}`}
      role={title ? 'img' : undefined}
      aria-hidden={title ? undefined : true}
      focusable="false"
      {...props}
    >
      {title && <title>{title}</title>}
      {paths.map((path) => (
        <path key={path.color} fill={path.color} d={path.d} />
      ))}
    </svg>
  )
}
